// @ts-check

import * as orders_model from "../model/orders.js";
import * as restaurants from "../model/restaurants.js";
import * as products from "../model/products.js";
import { getAuthUserId } from "../middleware/auth.js";
import { get_recommender } from "../service/recommender.js";

/** @typedef {import("../model/orders.js").Order} Order */

// An order may be cancelled only within this window after it was placed.
const CANCEL_WINDOW_MS = 15 * 60 * 1000;

/**
 * Parse an order's "YYYY-MM-DD hh:mm" created_at (local time) into epoch ms.
 * @param {string} created_at
 * @returns {number}
 */
const placed_at_ms = (created_at) => new Date(created_at.replace(" ", "T")).getTime();

/**
 * @param {unknown} value
 * @returns {value is number[]} whether value is an array of product ids (numbers).
 */
const is_product_id_array = (value) =>
  Array.isArray(value) && value.every((item) => typeof item === "number");

/**
 * Fetch an order only if it belongs to the logged in user. 
 * Like the real Wolt- a user can only see or act on their own orders.
 * Returns null both when the order does not exist and when it belongs to someone else- 
 * 404 in both cases.
 * @param {import("express").Request} req
 * @param {number} id
 * @returns {Promise<Order | null>}
 */
const own_order = async (req, id) => {
  const order = await orders_model.get_by_id(id);
  if (order === null || order.user !== getAuthUserId(req)) return null;
  return order;
};

/**
 * GET/api/orders- every order belonging to the logged in user.
 * @type {import("express").RequestHandler}
 */
const list_orders = async (req, res) => {
    const user = getAuthUserId(req);
    res.status(200).json(await orders_model.get_by_user(user));
    return;
};

/**
 * POST/api/orders- create an order for the logged in user.
 * The user comes from auth. id and created_at are generated by the model.
 * Restaurant and content are validated as types, then checked against the restaurant
 * and product models so you can't order a restaurant or product that doesn't exist
 * (like real Wolt). A product is checked within the restaurant- it must be on that
 * restaurant's menu.
 * Placing the order (buying) records the products to the recommendation.
 * @type {import("express").RequestHandler}
 */
const create_order = async (req, res) => {
  const user = getAuthUserId(req);
  const body = req.body;
  const restaurant = body?.restaurant;
  const content = body?.content;

  if (typeof restaurant !== "number" || !is_product_id_array(content)) {
    res.status(400).json({
      error: "restaurant must be a number and content an array of product ids",
    });
    return;
  }

  // An order must have at least one product like the real wolt (no empty orders).
  if (content.length === 0) {
    res.status(400).json({ error: "an order must contain at least one product" });
    return;
  }

  if ((await restaurants.getRestaurantById(restaurant)) === undefined) {
    res.status(400).json({ error: "unknown restaurant" });
    return;
  }
  let unknown;
  for (const product of content) {
    if ((await products.get(restaurant, product)) === null) {
      unknown = product;
      break;
    }
  }
  if (unknown !== undefined) {
    res.status(400).json({ error: `unknown product: ${unknown}` });
    return;
  }

  // Buying records the products to the recommendation engine (ex2). The product ids
  // are global, so the restaurant id isn't needed. We record FIRST and only persist
  // the order if recording succeeds, so a recommender failure never leaves a phantom
  // order behind. A failure is reported as 500 instead of being silently ignored.
  const recommend_error = await get_recommender()(user, content);
  if (recommend_error) {
    res.status(500).json(recommend_error);
    return;
  }

  const order = await orders_model.add({ user, restaurant, content });
  // Return the id in the body too (not just the Location header): browsers don't
  // expose Location on cross-origin responses, so clients on another origin
  // (e.g. the Expo web app) can still read the new order's id.
  res.status(201).location(`/api/orders/${order.id}`).json({ id: order.id });
};

/**
 * GET/api/orders/:id- a specific order only if it is the caller's own.
 * @type {import("express").RequestHandler}
 */
const get_order = async (req, res) => {
  const order = await own_order(req, Number(req.params.id));

  if (order === null) {
    res.status(404).json({ error: "order not found" });
    return;
  }

  res.status(200).json(order);
};

/**
 * PATCH/api/orders/:id- modify an order's product list (content only),
 * only if it is the caller's own.
 * The new products are checked against the product model too, within the order's restaurant.
 * Editing records the new products to the recommendations as well- the order's
 * items are what the user is buying, so the recommendation must reflect them.
 * @type {import("express").RequestHandler}
 */
const update_order = async (req, res) => {
  const id = Number(req.params.id);
  const order = await own_order(req, id);

  if (order === null) {
    res.status(404).json({ error: "order not found" });
    return;
  }

  // Cancellation via PATCH { cancelled: true }. This reuses the existing
  // PATCH /orders/:id route (no new route needed) and keeps the order in
  // history, just flagged cancelled- only allowed within 15 minutes of placing.
  if (req.body?.cancelled === true) {
    if (order.cancelled) {
      res.status(200).json(order);
      return;
    }
    if (Date.now() - placed_at_ms(order.created_at) > CANCEL_WINDOW_MS) {
      res.status(403).json({ error: "cant cancel an order after 15 minutes" });
      return;
    }
    const updated = await orders_model.set_cancelled(id);
    res.status(200).json(updated);
    return;
  }

  const content = req.body?.content;
  if (!is_product_id_array(content)) {
    res.status(400).json({ error: "content must be an array of product ids" });
    return;
  }

  // An order can't be emptied- delete it instead.
  if (content.length === 0) {
    res.status(400).json({ error: "an order must contain at least one product" });
    return;
  }

  let unknown;
  for (const product of content) {
    if ((await products.get(order.restaurant, product)) === null) {
      unknown = product;
      break;
    }
  }
  if (unknown !== undefined) {
    res.status(400).json({ error: `unknown product: ${unknown}` });
    return;
  }

  // Editing changes what the user is buying, so record the new products first and
  // only apply the change if recording succeeds (no half-applied edits on failure).
  // ex2 keeps a set per user so resending products already there is harmless.
  const recommend_error = await get_recommender()(order.user, content);
  if (recommend_error) {
    res.status(500).json(recommend_error);
    return;
  }

  await orders_model.set_content(id, content);
  res.status(204).end();
};

/**
 * DELETE/api/orders/:id- delete an order by id, only if it is the caller's own.
 * Cancelling doesnt touch recommendations.
 * @type {import("express").RequestHandler}
 */
const delete_order = async (req, res) => {
  const id = Number(req.params.id);
  const order = await own_order(req, id);

  if (order === null) {
    res.status(404).json({ error: "order not found" });
    return;
  }

  await orders_model.remove(id);
  res.status(204).end();
};

/**
 * POST/api/orders/:id/cancel- cancel an order, only if it is the caller's own and
 * only within 15 minutes of when it was placed. The order stays in history, just
 * flagged as cancelled (so it still shows on the past orders page, marked).
 * Cancelling doesnt touch recommendations.
 * @type {import("express").RequestHandler}
 */
const cancel_order = async (req, res) => {
  const id = Number(req.params.id);
  const order = await own_order(req, id);

  if (order === null) {
    res.status(404).json({ error: "order not found" });
    return;
  }

  // Already cancelled- idempotent, just report the current state.
  if (order.cancelled) {
    res.status(200).json(order);
    return;
  }

  // The cancel window closes 15 minutes after the order was placed.
  if (Date.now() - placed_at_ms(order.created_at) > CANCEL_WINDOW_MS) {
    res.status(403).json({ error: "cant cancel an order after 15 minutes" });
    return;
  }

  const updated = await orders_model.set_cancelled(id);
  res.status(200).json(updated);
};

export { list_orders, create_order, get_order, update_order, delete_order, cancel_order };